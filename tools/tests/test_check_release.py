"""Exercise release identity failures without building or publishing artifacts."""
import importlib.util
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch

SPEC = importlib.util.spec_from_file_location("check_release", Path(__file__).resolve().parents[1] / "check_release.py")
CHECK = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(CHECK)


class ReleaseIdentity(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.version = "1.0.0"
        self.write("Cargo.toml", '[workspace]\nresolver = "2"\nmembers = ["crates/drmr", "crates/drmr-core"]\n\n[workspace.package]\nversion = "1.0.0"\nedition = "2021"\n')
        for name in ("drmr", "drmr-core"):
            self.write("crates/" + name + "/Cargo.toml", '[package]\nname = "' + name + '"\nversion.workspace = true\nedition.workspace = true\n')
            self.write("crates/" + name + "/src/lib.rs", "")
        self.write("Cargo.lock", '# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = "drmr"\nversion = "1.0.0"\n\n[[package]]\nname = "drmr-core"\nversion = "1.0.0"\n')
        self.write("crates/drmr-desktop/tauri.conf.json", json.dumps({"version": self.version}))
        self.write("CHANGELOG.md", "# Changelog\n\n## [Unreleased]\n\n## [1.0.0] - 2026-10-22\n\n- Initial stable release.\n")

    def write(self, name, content):
        destination = self.root / name
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content, encoding="utf-8")

    def replace(self, name, old, new):
        path = self.root / name
        path.write_text(path.read_text(encoding="utf-8").replace(old, new), encoding="utf-8")

    def check(self, **kwargs):
        return CHECK.check_release(self.root, **kwargs)

    def git(self, *args):
        return subprocess.run(["git", *args], cwd=self.root, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE).stdout.decode().strip()

    def initialize_git(self):
        self.git("init", "--quiet")
        self.git("add", ".")
        self.git("-c", "user.name=Release Test", "-c", "user.email=release-test@example.invalid", "commit", "--quiet", "-m", "Release fixture")
        self.git("tag", "v1.0.0")

    def test_repository_mode_does_not_require_a_tag(self):
        report = self.check()
        self.assertTrue(report["success"])
        self.assertEqual(report["version"], self.version)
        self.assertIsNone(report["tag"])
        self.assertEqual(report["packages"], ["drmr", "drmr-core"])

    def test_expected_final_tag_must_match_product_version(self):
        self.assertEqual(self.check(tag="v1.0.0")["tag"], "v1.0.0")
        with self.assertRaisesRegex(CHECK.Failure, "tag-version-mismatch"):
            self.check(tag="v2.0.0")

    def test_malformed_tags_are_refused_without_echoing_input(self):
        for tag in ("1.0.0", "v01.0.0", "v1.0", "v1.0.0-rc.1", "v1.0.0+build", "v1.0.0\n", "--help", "v١.0.0"):
            with self.subTest(tag=tag), self.assertRaisesRegex(CHECK.Failure, "^tag-invalid$"):
                self.check(tag=tag)

    def test_root_product_version_requires_a_final_semantic_version(self):
        self.replace("Cargo.toml", 'version = "1.0.0"', 'version = "01.0.0"')
        with self.assertRaisesRegex(CHECK.Failure, "workspace-version-invalid"):
            self.check()

    def test_package_version_override_is_refused_even_when_equal(self):
        self.replace("crates/drmr-core/Cargo.toml", "version.workspace = true", 'version = "1.0.0"')
        with self.assertRaisesRegex(CHECK.Failure, "package-version-not-inherited"):
            self.check()

    def test_member_version_drift_is_refused(self):
        self.replace("crates/drmr-core/Cargo.toml", "version.workspace = true", 'version = "2.0.0"')
        with self.assertRaises(CHECK.Failure):
            self.check()

    def test_lock_package_version_drift_is_refused(self):
        self.replace("Cargo.lock", 'name = "drmr-core"\nversion = "1.0.0"', 'name = "drmr-core"\nversion = "0.9.0"')
        with self.assertRaises(CHECK.Failure):
            self.check()

    def test_missing_lock_package_is_refused(self):
        self.replace("Cargo.lock", '\n[[package]]\nname = "drmr-core"\nversion = "1.0.0"\n', "\n")
        with self.assertRaises(CHECK.Failure):
            self.check()

    def test_duplicate_local_lock_package_is_refused(self):
        path = self.root / "Cargo.lock"
        path.write_text(path.read_text() + '\n[[package]]\nname = "drmr-core"\nversion = "1.0.0"\n')
        with self.assertRaises(CHECK.Failure):
            self.check()

    def test_generated_registry_package_with_same_name_is_not_a_workspace_identity(self):
        path = self.root / "Cargo.lock"
        path.write_text(path.read_text() + '\n[[package]]\nname = "drmr-core"\nversion = "9.0.0"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\nchecksum = "' + "0" * 64 + '"\n')
        self.assertTrue(self.check()["success"])

    def test_tauri_version_mismatch_is_refused(self):
        self.write("crates/drmr-desktop/tauri.conf.json", '{"version":"0.9.0"}')
        with self.assertRaisesRegex(CHECK.Failure, "desktop-version-mismatch"):
            self.check()

    def test_duplicate_tauri_version_is_refused(self):
        self.write("crates/drmr-desktop/tauri.conf.json", '{"version":"0.9.0","version":"1.0.0"}')
        with self.assertRaisesRegex(CHECK.Failure, "duplicate-json-member"):
            self.check()

    def test_latest_changelog_release_must_match_version(self):
        self.replace("CHANGELOG.md", "## [1.0.0]", "## [0.9.0]")
        with self.assertRaisesRegex(CHECK.Failure, "changelog-version-mismatch"):
            self.check()

    def test_old_release_heading_does_not_mask_latest_mismatch(self):
        self.replace("CHANGELOG.md", "## [1.0.0]", "## [0.9.0]")
        with (self.root / "CHANGELOG.md").open("a") as stream:
            stream.write("\n## [1.0.0] - 2026-10-21\n\n- Older entry.\n")
        with self.assertRaisesRegex(CHECK.Failure, "changelog-version-mismatch"):
            self.check()

    def test_changelog_date_is_a_real_iso_date(self):
        self.replace("CHANGELOG.md", "2026-10-22", "2026-02-30")
        with self.assertRaisesRegex(CHECK.Failure, "changelog-header-invalid"):
            self.check()

    def test_duplicate_changelog_version_is_refused(self):
        with (self.root / "CHANGELOG.md").open("a") as stream:
            stream.write("\n## [1.0.0] - 2026-10-21\n\n- Repeated release.\n")
        with self.assertRaisesRegex(CHECK.Failure, "changelog-version-duplicate"):
            self.check()

    def test_cli_exact_stdout_and_empty_stderr_are_required(self):
        binary = self.root / "drmr"
        with patch.object(CHECK, "run", return_value=b"drmr 1.0.0\n") as command:
            CHECK.check_cli(binary, self.version)
        self.assertEqual(command.call_args.args[0], [str(binary), "--version"])
        self.assertTrue(command.call_args.kwargs["empty_stderr"])

    def test_cli_wrong_banner_and_extra_output_are_refused(self):
        for output in (b"drmr 0.9.0\n", b"other 1.0.0\n", b"drmr 1.0.0\nprivate fixture\n", b"drmr 1.0.0\x00"):
            with self.subTest(output=output), patch.object(CHECK, "run", return_value=output), self.assertRaisesRegex(CHECK.Failure, "cli-version-mismatch"):
                CHECK.check_cli(self.root / "drmr", self.version)

    def test_cli_failure_does_not_echo_subprocess_output(self):
        result = subprocess.CompletedProcess(["fixture"], 1, stdout=b"private fixture", stderr=b"private fixture")
        with patch.object(CHECK.subprocess, "run", return_value=result), self.assertRaisesRegex(CHECK.Failure, "^cli-command-failed$"):
            CHECK.check_cli(self.root / "drmr", self.version)

    def test_cli_stderr_is_refused_even_with_successful_exit(self):
        result = subprocess.CompletedProcess(["fixture"], 0, stdout=b"drmr 1.0.0\n", stderr=b"private fixture")
        with patch.object(CHECK.subprocess, "run", return_value=result), self.assertRaisesRegex(CHECK.Failure, "^cli-command-failed$"):
            CHECK.check_cli(self.root / "drmr", self.version)

    def test_cli_timeout_is_sanitized(self):
        error = subprocess.TimeoutExpired(["fixture"], 30, output=b"private fixture", stderr=b"private fixture")
        with patch.object(CHECK.subprocess, "run", side_effect=error), self.assertRaisesRegex(CHECK.Failure, "^cli-command-failed$"):
            CHECK.check_cli(self.root / "drmr", self.version)

    def test_publication_requires_an_explicit_tag(self):
        with self.assertRaisesRegex(CHECK.Failure, "tag-required"):
            self.check(require_tag=True)

    def test_clean_exact_local_tag_is_accepted(self):
        self.initialize_git()
        report = self.check(tag="v1.0.0", require_tag=True)
        self.assertEqual(report["commit"], self.git("rev-parse", "HEAD"))
        self.assertTrue(report["tag_verified"])

    def test_annotated_release_tag_is_peeled_to_the_commit(self):
        self.initialize_git()
        self.git("tag", "-d", "v1.0.0")
        self.git("-c", "user.name=Release Test", "-c", "user.email=release-test@example.invalid", "tag", "-a", "v1.0.0", "-m", "Release fixture")
        self.assertTrue(self.check(tag="v1.0.0", require_tag=True)["tag_verified"])

    def test_tag_on_another_commit_is_refused(self):
        self.initialize_git()
        self.write("tracked.txt", "second commit\n")
        self.git("add", "tracked.txt")
        self.git("-c", "user.name=Release Test", "-c", "user.email=release-test@example.invalid", "commit", "--quiet", "-m", "Next fixture")
        with self.assertRaisesRegex(CHECK.Failure, "tag-commit-mismatch"):
            self.check(tag="v1.0.0", require_tag=True)

    def test_missing_tag_is_refused(self):
        self.initialize_git()
        self.git("tag", "-d", "v1.0.0")
        with self.assertRaisesRegex(CHECK.Failure, "tag-command-failed"):
            self.check(tag="v1.0.0", require_tag=True)

    def test_dirty_tracked_tree_is_refused(self):
        self.initialize_git()
        self.write("crates/drmr/src/lib.rs", "// changed fixture\n")
        with self.assertRaisesRegex(CHECK.Failure, "working-tree-dirty"):
            self.check(tag="v1.0.0", require_tag=True)

    def test_untracked_file_is_refused(self):
        self.initialize_git()
        self.write("untracked.txt", "fixture\n")
        with self.assertRaisesRegex(CHECK.Failure, "working-tree-dirty"):
            self.check(tag="v1.0.0", require_tag=True)

    def test_cli_entrypoint_failure_report_is_fixed_json(self):
        result = subprocess.run([sys.executable, str(Path(CHECK.__file__)), "--root", str(self.root), "--tag", "private fixture"], stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=False)
        self.assertEqual(result.returncode, 1)
        self.assertEqual(json.loads(result.stdout), {"schema_version": 1, "success": False, "error": "tag-invalid"})
        self.assertEqual(result.stderr, b"")


if __name__ == "__main__":
    unittest.main()
